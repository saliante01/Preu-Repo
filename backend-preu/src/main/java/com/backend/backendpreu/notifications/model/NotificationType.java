package com.backend.backendpreu.notifications.model;

/**
 * Defines the type of a system notification.
 */
public enum NotificationType {

    /**
     * Notification related to academic meetings or sessions.
     */
    MEETING,

    /**
     * Notification related to evaluations or assessments.
     */
    EVALUATION,

    /**
     * Notification related to payment information.
     */
    PAYMENT,

    /**
     * General informational notification.
     */
    INFO
}
